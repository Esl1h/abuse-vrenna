#!/bin/sh
# Changelog from Conventional Commit subjects.
#
#   scripts/changelog.sh        every release since the fork, newest first, with
#                               what is not released yet on top. This is what
#                               CHANGELOG.md holds:
#                                   scripts/changelog.sh > CHANGELOG.md
#   scripts/changelog.sh REF    only what REF brought in, from the tag before it
#                               to REF (a tag, or HEAD for what is unreleased).
#                               This is the text for a GitHub Release.
#
# Merge commits are skipped, and a subject that is not a Conventional Commit
# lands under "Other". The history before the fork (upstream-sdl3-base and
# everything under it) is Xenoveritas's and is not listed.
set -eu

base=upstream-sdl3-base
git rev-parse -q --verify "$base" >/dev/null \
    || { echo "changelog: the tag $base is missing; fetch the tags" >&2; exit 1; }

# Our releases only: the upstream tags (v0.9.0, v0.9.1) are reachable from the base.
tags=$(git tag --no-merged "$base" --sort=creatordate 'v*')

# The commits in FROM..TO, grouped by what they say they are.
body() {
    git log --no-merges --format='%h%x09%s' "$1..$2" | awk -F '\t' '
    BEGIN {
        n = split("feat fix perf refactor docs test maintenance other", order, " ")
        title["feat"] = "Features"
        title["fix"] = "Fixes"
        title["perf"] = "Performance"
        title["refactor"] = "Refactoring"
        title["docs"] = "Documentation"
        title["test"] = "Tests"
        title["maintenance"] = "Build and CI"
        title["other"] = "Other"
        group["build"] = group["ci"] = group["chore"] = group["style"] = "maintenance"
        for (i = 1; i <= 5; i++) group[order[i]] = order[i]
        group["test"] = "test"
    }
    {
        hash = $1
        subject = $2
        for (i = 3; i <= NF; i++) subject = subject "\t" $i
        kind = "other"; scope = ""; breaking = 0; text = subject
        if (match(subject, /^[a-z]+(\([^)]*\))?!?: /)) {
            head = substr(subject, 1, RLENGTH - 2)
            text = substr(subject, RLENGTH + 1)
            if (head ~ /!$/) { breaking = 1; sub(/!$/, "", head) }
            if (match(head, /\(.*\)$/)) {
                scope = substr(head, RSTART + 1, RLENGTH - 2)
                head = substr(head, 1, RSTART - 1)
            }
            if (head in group) kind = group[head]
        }
        line = "- "
        if (breaking) line = line "**BREAKING** "
        if (scope != "") line = line "**" scope "**: "
        line = line text " (" hash ")"
        count[kind]++
        lines[kind, count[kind]] = line
    }
    END {
        for (i = 1; i <= n; i++) {
            k = order[i]
            if (!count[k]) continue
            printf "### %s\n\n", title[k]
            for (j = 1; j <= count[k]; j++) print lines[k, j]
            print ""
        }
    }'
}

# The tag made before $1, or the base for the first release. A $1 that is not
# a tag (HEAD) gets the newest one.
previous_of() {
    prev=$base
    for t in $tags; do
        if [ "$t" = "$1" ]; then
            break
        fi
        prev=$t
    done
    echo "$prev"
}

if [ $# -ge 1 ]; then
    body "$(previous_of "$1")" "$1"
    exit 0
fi

echo "# Changelog"
echo
echo "Generated by scripts/changelog.sh from the commit subjects. Do not edit it"
echo "by hand: run the script again."
echo

last=""
for t in $tags; do last=$t; done
if [ -n "$last" ] && [ -n "$(git log --no-merges --format=%h "$last..HEAD" | head -1)" ]; then
    echo "## Unreleased"
    echo
    body "$last" HEAD
fi

# Newest first.
ordered=""
for t in $tags; do
    ordered="$t $ordered"
done
for t in $ordered; do
    prev=$(previous_of "$t")
    echo "## $t ($(git log -1 --format=%cs "$t"))"
    echo
    body "$prev" "$t"
done
